export interface CreativePlan {
  id: string;
  emoji: string;
  name: string;
  /** Placement format, e.g. "וידאו 15–30 שניות · 9:16". */
  format: string;
  /** The Russian-market pattern this creative mirrors, and why it wins. */
  inspiration: string;
  /** First line / first two seconds — the scroll-stopper. */
  hook: string;
  /** Full primary text for the ad, ready to paste. */
  primaryText: string;
  headline: string;
  description: string;
  cta: string;
  /** Filming/production brief — every shot is doable with one phone. */
  shotList: string[];
}

export interface AdSetPlan {
  id: string;
  emoji: string;
  name: string;
  dailyBudget: number;
  audience: string[];
  geo: string[];
  creativeIds: string[];
  notes: string;
}

