-- 2. רשימת הערים בסינון נקראה עד היום מאלף השורות הראשונות של המאגר
--    ו-DISTINCT עליהן בדפדפן. במאגר של 1,354 קבוצות זה כבר מחמיץ ערים, ועם
--    כל הארץ זה היה מחמיץ את רובן. הפונקציה כאן מחזירה את הערכים והספירות
--    מהמסד עצמו, בשאילתה אחת.
--
-- ─── אפשר להריץ פעמיים ─────────────────────────────────────────────────────

-- ─── 1. הערכים לסינון, מהמסד ולא מדגימה ──────────────────────────────────
--
-- security invoker: הפונקציה רצה בהרשאות של מי שקרא לה, ולכן אותה מדיניות
-- RLS שחלה על הטבלה חלה גם כאן. היא לא פותחת שום דלת חדשה.
create or replace function public.social_catalog_facets()
returns table (kind text, value text, groups bigint)
language sql
stable
security invoker
set search_path = public
as $$
  select 'city'::text, city, count(*) from public.social_group_catalog where city <> '' group by city
  union all
  select 'region'::text, region, count(*) from public.social_group_catalog where region <> '' group by region
  union all
  select 'language'::text, language, count(*) from public.social_group_catalog where language <> '' group by language
  union all
  select 'category'::text, category, count(*) from public.social_group_catalog where category <> '' group by category
$$;

revoke all on function public.social_catalog_facets() from public;
grant execute on function public.social_catalog_facets() to authenticated;

